const BOOK_NAMES = BIBLE_BOOKS.map((b) => b.name)

export function getBibleBooks(): string[] { return BOOK_NAMES }

export function getChapterCount(bookName: string): number | null {
  const book = BIBLE_BOOKS.find((b) => b.name === bookName)
  return book ? book.chapters.length : null
}

export function getVerseCount(bookName: string, chapter: number): number | null {
  const book = BIBLE_BOOKS.find((b) => b.name === bookName)
  if (!book || chapter < 1 || chapter > book.chapters.length) return null
  return book.chapters[chapter - 1]
}
